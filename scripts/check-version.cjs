const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = path => fs.readFileSync(path, 'utf8');
const {version, buildNumber} = JSON.parse(read('version.json'));
assert.match(version, /^\d+\.\d+\.\d+(?:-(?:alpha|beta|rc)\.\d+)?$/);
assert.ok(Number.isSafeInteger(buildNumber) && buildNumber > 400);
const pkg = JSON.parse(read('package.json'));
const lock = JSON.parse(read('package-lock.json'));
assert.equal(pkg.version, version);
assert.equal(lock.version, version);
assert.equal(lock.packages[''].version, version);
assert.equal(lock.packages[''].engines.node, pkg.engines.node);
const gradle = read('android/app/build.gradle');
assert.equal(gradle.match(/versionName "([^"]+)"/)[1], version);
assert.equal(Number(gradle.match(/versionCode (\d+)/)[1]), buildNumber);
const ios = read('ios/MonzoBot.xcodeproj/project.pbxproj');
const marketing = [...ios.matchAll(/MARKETING_VERSION = ([^;]+);/g)];
const builds = [...ios.matchAll(/CURRENT_PROJECT_VERSION = (\d+);/g)];
assert.equal(marketing.length, 2);
assert.equal(builds.length, 2);
for (const m of marketing) assert.equal(m[1], version.split('-')[0]);
for (const b of builds) assert.equal(Number(b[1]), buildNumber);
assert.ok(read('CHANGELOG.md').includes('## '+version));
console.log(`Version aligned: ${version}, build ${buildNumber} (iOS metadata only; scaffold not released)`);
